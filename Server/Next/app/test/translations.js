export function translateQuestion(questions, language) {
    if (language !== "kk") return questions;
    const translate = (text) => questionText[text] ?? text;
    const option = (item) => ({ ...item, text: translate(item.text) });
    return questions.map((item) => ({
        ...item,
        question: translate(item.question),
        ...(item.text && { text: translate(item.text) }),
        ...(item.answers && { answers: item.answers.map(option) }),
        ...(item.left && { left: option(item.left), right: option(item.right) })
    }));
}

