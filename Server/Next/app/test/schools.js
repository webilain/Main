export const schools = schoolGroups.flatMap((group) => group.schools);

function normalizeSearch(text) {
    return text.toLowerCase().replaceAll("ё", "е");
}

export function searchSchools(query) {
    const terms = normalizeSearch(query).match(/[\p{L}\p{N}]+/gu) ?? [];
    if (terms.length === 0) return schoolGroups;

    const schoolNumber = query.match(/^\s*(?:№\s*)?(\d+)\s*$/)?.[1];
    return schoolGroups.map((group) => ({
        ...group,
        schools: group.schools.filter((school) => {
            if (schoolNumber) return school.id === `school-${schoolNumber}` || school.ru.endsWith(`№${schoolNumber}`);
            const text = normalizeSearch([school.ru, school.kk, school.value, ...Object.values(school.address)].join(" "));
            const words = text.match(/[\p{L}\p{N}]+/gu) ?? [];
            return terms.every((term) => /^\d+$/.test(term) ? words.includes(term) : text.includes(term));
        })
    }));
}
